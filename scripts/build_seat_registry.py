#!/usr/bin/env python3
"""Build assets/data/seats.json: every elected seat VoteGA tracks and the maps that drew it.

Phase 1 of docs/seat-history-design.md. A districted seat is its set of census blocks,
so which districts a new map carried over is measured from the reapportionment office's
block-equivalency files, never assumed from the district numbers.

Two steps, because the block files are large and not committed:

  1. On redistricting only (needs the local inputs in data-inputs/redistricting/):
       python scripts/build_seat_registry.py --compare
     compares each plan with the one before it and writes the committed
     scripts/data/seat-plan-comparison.json (with each input's MD5).

  2. Any time, from committed files only:
       python scripts/build_seat_registry.py          # write assets/data/seats.json
       python scripts/build_seat_registry.py --check  # exit 1 if the committed file is stale
     reads scripts/data/seat-plans.json, the comparison, and
     assets/data/ga-executive-seats.json (the statewide seats). It refuses to write a
     registry that fails scripts/lib/seat_registry.registry_errors, including the
     append-only check against the committed file. A run that changes nothing keeps
     generatedAt, so a quiet rebuild is byte-identical.

Stdlib only (the xlsx reader is scripts/lib/xlsx_rows.py), so the offline CI job can run --check.
"""
import argparse
import hashlib
import json
import os
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib.atomic_io import write_json_atomic  # noqa: E402
from lib.seat_registry import (build_seats, compare_plans, plan_summaries,  # noqa: E402
                               plans_by_body, registry_errors)
from lib.xlsx_rows import read_rows  # noqa: E402

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLANS_FILE = os.path.join(REPO_ROOT, "scripts", "data", "seat-plans.json")
COMPARISON_FILE = os.path.join(REPO_ROOT, "scripts", "data", "seat-plan-comparison.json")
EXECUTIVE_SEATS_FILE = os.path.join(REPO_ROOT, "assets", "data", "ga-executive-seats.json")
OUTPUT_FILE = os.path.join(REPO_ROOT, "assets", "data", "seats.json")


def load(path, default=None):
    if not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def md5(path):
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_block_equivalency(path):
    """{15-digit block GEOID: district int} from a reapportionment office workbook."""
    rows = read_rows(path)
    header = next(rows)
    if not header or str(header[0]).strip().lower() != "block":
        raise SystemExit(f"Error: {path}: expected a 'Block' column first, got {header!r}")
    out = {}
    for row in rows:
        if len(row) < 2 or not row[0]:
            continue
        block, district = str(row[0]).strip(), str(row[1]).strip()
        if len(block) != 15 or not block.isdigit():
            raise SystemExit(f"Error: {path}: {block!r} is not a 15-digit block GEOID")
        out[block] = int(float(district))
    return out


def run_compare(plans_doc):
    result = {"_comment": ("GENERATED by scripts/build_seat_registry.py --compare from the "
                           "block-equivalency files named in seat-plans.json. Do not hand-edit."),
              "generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
              "plans": {}}
    for body, chain in plans_by_body(plans_doc["plans"]).items():
        for old, new in zip(chain, chain[1:]):
            paths = [os.path.join(REPO_ROOT, p["source"]) for p in (old, new)]
            for path in paths:
                if not os.path.exists(path):
                    raise SystemExit(f"Error: {path} is missing; see data-inputs/README.md "
                                     "for where to download it")
            old_bef, new_bef = (read_block_equivalency(p) for p in paths)
            n = plans_doc["bodies"][body]["districts"]
            for label, bef in ((old["id"], old_bef), (new["id"], new_bef)):
                if sorted(set(bef.values())) != list(range(1, n + 1)):
                    raise SystemExit(f"Error: {label} does not have districts 1..{n}")
            try:
                cmp_ = compare_plans(old_bef, new_bef)
            except ValueError as e:
                raise SystemExit(f"Error: {old['id']} -> {new['id']}: {e}")
            cmp_["comparedWith"] = old["id"]
            cmp_["inputs"] = {p["source"]: md5(path) for p, path in zip((old, new), paths)}
            result["plans"][new["id"]] = cmp_
            print(f"{old['id']} -> {new['id']}: {len(cmp_['carriedOver'])} carried over, "
                  f"{len(cmp_['newlyDrawn'])} newly drawn, renumbered identical "
                  f"{cmp_['renumberedIdentical']}, {cmp_['blocksThatChangedDistrict']} blocks moved")
    old = load(COMPARISON_FILE)
    if old and {k: v for k, v in old.items() if k != "generatedAt"} == \
            {k: v for k, v in result.items() if k != "generatedAt"}:
        print(f"{COMPARISON_FILE} unchanged")
        return
    write_json_atomic(COMPARISON_FILE, result, indent=2)
    print(f"Wrote {COMPARISON_FILE}")


def build_registry(plans_doc, comparison, executive_seats):
    seats = build_seats(plans_doc, comparison["plans"], executive_seats)
    return {
        "metadata": {
            "generatedAt": None,
            "count": len(seats),
            "schemaVersion": 1,
            "meaning": ("Every seat VoteGA tracks. A districted seat is its set of census "
                        "blocks: its id carries the map that FIRST drew it (`plan`) and is never "
                        "renamed; `redrawnBy` names the map that replaced it, null while in force. "
                        "A district a later map left untouched keeps its seat. Holders are not "
                        "here (Phase 2)."),
            "sources": [
                "Georgia Legislative and Congressional Reapportionment Office block-equivalency "
                "files (compared in scripts/data/seat-plan-comparison.json)",
                "assets/data/ga-executive-seats.json (statewide seats)",
            ],
            "plans": plan_summaries(plans_doc, comparison["plans"]),
        },
        "seats": seats,
    }


def same_content(a, b):
    strip = lambda d: {**d, "metadata": {k: v for k, v in d["metadata"].items() if k != "generatedAt"}}  # noqa: E731
    return a is not None and b is not None and strip(a) == strip(b)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--compare", action="store_true",
                    help="re-measure carried-over districts from the block files (needs data-inputs/)")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if assets/data/seats.json does not match a rebuild")
    args = ap.parse_args()

    plans_doc = load(PLANS_FILE)
    if args.compare:
        run_compare(plans_doc)
        return 0
    comparison = load(COMPARISON_FILE)
    if comparison is None:
        raise SystemExit(f"Error: {COMPARISON_FILE} is missing; run with --compare first")
    executive = load(EXECUTIVE_SEATS_FILE)["seats"]
    reg = build_registry(plans_doc, comparison, executive)
    committed = load(OUTPUT_FILE)

    errs = registry_errors(reg, plans_doc, comparison["plans"], executive, previous=committed)
    if errs:
        print("Refusing to write seats.json:", *errs, sep="\n  ", file=sys.stderr)
        return 1
    if args.check:
        if same_content(reg, committed):
            print(f"{OUTPUT_FILE} is up to date ({reg['metadata']['count']} seats)")
            return 0
        print(f"Error: {OUTPUT_FILE} is stale; run python scripts/build_seat_registry.py",
              file=sys.stderr)
        return 1
    if same_content(reg, committed):
        print(f"{OUTPUT_FILE} unchanged ({reg['metadata']['count']} seats)")
        return 0
    reg["metadata"]["generatedAt"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    write_json_atomic(OUTPUT_FILE, reg, indent=1)
    print(f"Wrote {OUTPUT_FILE}: {reg['metadata']['count']} seats")
    return 0


if __name__ == "__main__":
    sys.exit(main())
